import java.util.*;

public class AddressBookEntry
        implements Comparable<AddressBookEntry> {
    private String name;
    private String email;
    private String phone;

    private static final Comparator<AddressBookEntry> comp = Comparator.comparing(AddressBookEntry::getName)
                .thenComparing(AddressBookEntry::getEmail).thenComparing(AddressBookEntry::getPhone);

    public AddressBookEntry(String name, String email, String phone) {
        this.name = name;
        this.email = email;
        this.phone = phone;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getPhone() {
        return phone;
    }

    @Override
    public String toString() {
        return "name=" + name + ", email=" + email + ", phone=" + phone;
    }

    @Override
    public int compareTo(AddressBookEntry o) {
        
        return comp.compare(this, o);
    }

    @Override
    public int hashCode() {
        final int prime = 31;
        int result = 1;
        result = prime * result + ((name == null) ? 0 : name.hashCode());
        result = prime * result + ((email == null) ? 0 : email.hashCode());
        result = prime * result + ((phone == null) ? 0 : phone.hashCode());
        return result;
    }

    @Override
    public boolean equals(Object obj) {
        if (this == obj)
            return true;
        if (obj == null)
            return false;
        if (getClass() != obj.getClass())
            return false;
        AddressBookEntry other = (AddressBookEntry) obj;
        if (name == null) {
            if (other.name != null)
                return false;
        } else if (!name.equals(other.name))
            return false;
        if (email == null) {
            if (other.email != null)
                return false;
        } else if (!email.equals(other.email))
            return false;
        if (phone == null) {
            if (other.phone != null)
                return false;
        } else if (!phone.equals(other.phone))
            return false;
        return true;
    }

    
}
